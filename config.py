# ----------------------------------------------------------
# Общие PPO-гиперпараметры (одинаковы для MLP и CNN)
# ----------------------------------------------------------
_PPO_BASE = {
    "n_envs":          8,
    "total_timesteps": 5_000_000,
 
    # ИСПРАВЛЕНО: 3e-4 → 1e-4
    # При VecNormalize масштаб градиентов меняется — нужен меньший шаг
    "learning_rate":   1e-4,
 
    # ИСПРАВЛЕНО: 2048 → 4096
    # Больше шагов до обновления = более стабильная оценка advantage
    # Суммарный буфер = 4096 * 8 envs = 32768 переходов
    "n_steps":         4096,
 
    # ИСПРАВЛЕНО: 512 → 256
    # Меньший батч компенсирует меньший lr — градиенты более точные
    "batch_size":      256,
 
    "n_epochs":        10,
    "gamma":           0.99,
    "gae_lambda":      0.95,
    "clip_range":      0.2,
 
    # ИСПРАВЛЕНО: 0.03 → 0.005
    # Предыдущее значение давало entropy_loss=-2.14 (агент почти случаен).
    # Цель: entropy_loss в диапазоне -0.5..-1.0
    "ent_coef":        0.005,
 
    "vf_coef":         0.5,
    "max_grad_norm":   0.5,
}

