
# config.py  (v3 — исправлены гиперпараметры после диагностики)
#
# Проблемы предыдущей версии (зафиксированы при обучении):
#   explained_variance = -0.08  (норма > 0.5)
#   clip_fraction      = 0.288  (норма < 0.15)
#   entropy_loss       = -2.14  (слишком высокая, агент почти случаен)
#
# Причина: learning_rate=3e-4 слишком высокий при использовании VecNormalize.
# VecNormalize меняет масштаб наград, шаги обновления оказываются
# слишком крупными → критик расходится → gradient шумный.
#
# Изменения:
#   learning_rate: 3e-4  → 1e-4   (главное исправление)
#   ent_coef:      0.03  → 0.005  (уменьшаем случайность политики)
#   n_steps:       2048  → 4096   (больше данных до каждого обновления)
#   batch_size:    512   → 256    (меньше батч → более стабильный SGD с малым lr)
#   combo:         2.0   → 1.5    (смягчаем, но не убираем — сигнал нужен)
 
